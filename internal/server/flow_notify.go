// A Notify node delivers its input to the flow owner by email, or to the one
// chat webhook (Slack, Discord, Microsoft Teams or a generic JSON endpoint)
// a SYS_ADMIN configured. The webhook URL is a credential: it is sealed with
// FLOWEYSALES_SECRETS_KEY, never stored in a graph and never sent back to a
// browser. Sending is a side effect with capability notify.send, so it is
// audited and can require approval like Workspace writes.
const (
	capabilityNotifySend = "notify.send"
	notifyWebhookKind    = "notify_webhook"
	notifyEmailMaxBody   = 20000
	notifyDisclaimer     = "Research output generated by an automated FloweySales flow. Not investment advice."
)

var notifyWebhookProviders = map[string]bool{"slack": true, "discord": true, "teams": true, "generic": true}

// notifySubject fills {{flow}}, {{date}} and {{count}} in a subject line.
func notifySubject(template, flowName, payload string, now time.Time) string {
	subject := strings.TrimSpace(template)
	if subject == "" {
		subject = "FloweySales: {{flow}}"
	}
	count := ""
	if rows, err := flowRows(payload); err == nil {
		count = strconv.Itoa(len(rows))
	}
	subject = strings.NewReplacer("{{flow}}", flowName, "{{date}}", now.UTC().Format("2006-01-02"), "{{count}}", count).Replace(subject)
	subject = strings.Map(func(r rune) rune {
		if r < 32 {
			return ' '
		}
		return r
	}, subject)
	if len(subject) > 150 {
		subject = subject[:150]
	}
	return subject
}

// notifyBody renders JSON rows as a table and leaves text as it is.
func notifyBody(payload string) string {
	body := payload
	if rows, err := flowRows(payload); err == nil && len(rows) > 0 && strings.HasPrefix(strings.TrimSpace(payload), "[") {
		if table, err := reportTable(payload, "", "", 50); err == nil {
			body = table
		}
	}
	return strings.TrimSpace(body)
}

func truncateText(s string, max int) string {
	if len(s) <= max {
		return s
	}
	cut := max - 20
	for cut > 0 && cut < len(s) && (s[cut]&0xC0) == 0x80 {
		cut-- // Never split a UTF-8 sequence.
	}
	return s[:cut] + "\n… (truncated)"
}

// sendFlowNotification delivers one notification and describes the delivery.
func (e *Engine) sendFlowNotification(ctx context.Context, f storage.AgentFlow, n flowNode, payload string) (string, error) {
	now := time.Now()
	subject := notifySubject(n.Subject, f.Name, payload, now)
	body := notifyBody(payload)
	runID, _ := ctx.Value(flowTraceRunKey{}).(int64)
	footer := fmt.Sprintf("\n\n—\nFlow #%d %q", f.ID, f.Name)
	if runID > 0 {
		footer += fmt.Sprintf(", run #%d", runID)
	}
	footer += ". " + notifyDisclaimer
	switch n.Channel {
	case "email":
		if e.db == nil || e.authService == nil {
			return "", errors.New("email needs storage and authentication")
		}
		recipient, err := e.db.FlowOwnerEmail(ctx, f.ID)
		if err != nil {
			return "", fmt.Errorf("flow owner email unavailable: %w", err)
		}
		cfg, err := e.authService.GetSMTPSettings(ctx)
		if err != nil || !validSMTP(cfg) {
			return "", errors.New("SMTP is not configured: a SYS_ADMIN sets it up under Settings → Email")
		}
		saved, err := e.db.GetAPIIntegrationSecret(ctx, "smtp")
		if err != nil {
			return "", errors.New("SMTP password is not configured")
		}
		password, err := openAPISecret("smtp", saved.Ciphertext)
		if err != nil {
			return "", err
		}
		mailCtx, cancel := context.WithTimeout(ctx, 25*time.Second)
		defer cancel()
		if err := sendTrackerEmail(mailCtx, cfg.Host, cfg.Port, cfg.Username, cfg.Sender, password, recipient, subject, truncateText(body, notifyEmailMaxBody)+footer); err != nil {
			return "", fmt.Errorf("email delivery failed: %w", err)
		}
		return "Emailed " + recipient + ": " + subject, nil
	case "webhook":
		provider, target, err := e.notifyWebhook(ctx)
		if err != nil {
			return "", err
		}
		if err := postNotifyWebhook(ctx, provider, target, subject, body, footer, f, runID); err != nil {
			return "", err
		}
		return "Posted to the " + provider + " webhook: " + subject, nil
	}
	return "", fmt.Errorf("unknown notification channel %q", n.Channel)
}

func (e *Engine) notifyWebhook(ctx context.Context) (string, string, error) {
	if e.db == nil {
		return "", "", errors.New("webhook notifications need storage")
	}
	saved, err := e.db.GetAPIIntegrationSecret(ctx, notifyWebhookKind)
	if storage.IsMissingAPIIntegration(err) {
		return "", "", errors.New("no notification webhook is configured: a SYS_ADMIN adds one under Flow Studio → Function library & triggers → Notifications")
	}
	if err != nil {
		return "", "", err
	}
	target, err := openAPISecret(notifyWebhookKind, saved.Ciphertext)
	if err != nil {
		return "", "", err
	}
	return saved.Provider, target, nil
}

// notifyWebhookPayload shapes the message for the chat service.
func notifyWebhookPayload(provider, subject, body, footer string, f storage.AgentFlow, runID int64) ([]byte, error) {
	switch provider {
	case "slack", "teams":
		return json.Marshal(map[string]string{"text": "*" + subject + "*\n" + truncateText(body, 3200) + footer})
	case "discord":
		return json.Marshal(map[string]any{"content": truncateText("**"+subject+"**\n"+body, 1800-len(footer)) + footer, "allowed_mentions": map[string]any{"parse": []string{}}})
	case "generic":
		return json.Marshal(map[string]any{"subject": subject, "text": truncateText(body, notifyEmailMaxBody), "flow_id": f.ID, "flow": f.Name, "run_id": runID, "disclaimer": notifyDisclaimer})
	}
	return nil, fmt.Errorf("unknown webhook provider %q", provider)
}

func validNotifyWebhookURL(raw string) (*url.URL, error) {
	u, err := flowPublicURL(strings.TrimSpace(raw))
	if err != nil {
		return nil, err
	}
	if u.Scheme != "https" {
		return nil, errors.New("webhook URL must use https")
	}
	return u, nil
}

func postNotifyWebhook(ctx context.Context, provider, target, subject, body, footer string, f storage.AgentFlow, runID int64) error {
	u, err := validNotifyWebhookURL(target)
	if err != nil {
		return fmt.Errorf("webhook URL refused: %w", err)
	}
	payload, err := notifyWebhookPayload(provider, subject, body, footer, f, runID)
	if err != nil {
		return err
	}
	client, closeClient, err := flowPinnedClient(ctx, u)
	if err != nil {
		return err
	}
	defer closeClient()
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, u.String(), bytes.NewReader(payload))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "FloweySales-Flow-Notify/1")
	resp, err := client.Do(req)
	if err != nil {
		// The error text can contain the URL, which is a credential.
		return errors.New("webhook request failed")
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, 4096))
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return fmt.Errorf("webhook answered HTTP %d", resp.StatusCode)
	}
	return nil
}

func (e *Engine) registerFlowNotifyRoutes() {
	e.mux.HandleFunc("GET /api/admin/flow-notify-channels", func(w http.ResponseWriter, r *http.Request) {
		if !e.flowAdmin(w, r) {
			return
		}
		out := map[string]any{"email": map[string]any{"configured": false}, "webhook": map[string]any{"configured": false}}
		if e.authService != nil {
			if cfg, err := e.authService.GetSMTPSettings(r.Context()); err == nil && validSMTP(cfg) {
				out["email"] = map[string]any{"configured": true}
			}
		}
		if e.db != nil {
			if saved, err := e.db.GetAPIIntegrationSecret(r.Context(), notifyWebhookKind); err == nil {
				out["webhook"] = map[string]any{"configured": true, "provider": saved.Provider}
			}
		}
		writeJSON(w, 200, out)
	})
	e.mux.HandleFunc("PUT /api/admin/flow-notify-channels/webhook", func(w http.ResponseWriter, r *http.Request) {
		if !e.flowAdmin(w, r) {
			return
		}
		var body struct {
			Provider string `json:"provider"`
			URL      string `json:"url"`
		}
		if err := json.NewDecoder(io.LimitReader(r.Body, 8192)).Decode(&body); err != nil {
			writeJSON(w, 400, map[string]string{"error": "Invalid request"})
			return
		}
		if !notifyWebhookProviders[body.Provider] {
			writeJSON(w, 400, map[string]string{"error": "Provider must be slack, discord, teams or generic"})
			return
		}
		if _, err := validNotifyWebhookURL(body.URL); err != nil {
			writeJSON(w, 400, map[string]string{"error": "Webhook URL refused: " + err.Error()})
			return
		}
		sealed, err := sealAPISecret(notifyWebhookKind, strings.TrimSpace(body.URL))
		if err != nil {
			writeJSON(w, 503, map[string]string{"error": "Set FLOWEYSALES_SECRETS_KEY to store webhook URLs"})
			return
		}
		if err := e.db.SaveAPIIntegrationSecret(r.Context(), notifyWebhookKind, body.Provider, sealed); err != nil {
			writeJSON(w, 503, map[string]string{"error": "Cannot save webhook"})
			return
		}
		writeJSON(w, 200, map[string]any{"configured": true, "provider": body.Provider})
	})
	e.mux.HandleFunc("DELETE /api/admin/flow-notify-channels/webhook", func(w http.ResponseWriter, r *http.Request) {
		if !e.flowAdmin(w, r) {
			return
		}
		if err := e.db.DeleteAPIIntegrationSecret(r.Context(), notifyWebhookKind); err != nil {
			writeJSON(w, 503, map[string]string{"error": "Cannot remove webhook"})
			return
		}
		writeJSON(w, 200, map[string]bool{"deleted": true})
	})
	e.mux.HandleFunc("POST /api/admin/flow-notify-channels/test", func(w http.ResponseWriter, r *http.Request) {
		if !e.flowAdmin(w, r) {
			return
		}
		provider, target, err := e.notifyWebhook(r.Context())
		if err != nil {
			writeJSON(w, 400, map[string]string{"error": err.Error()})
			return
		}
		ctx, cancel := context.WithTimeout(r.Context(), 20*time.Second)
		defer cancel()
		test := storage.AgentFlow{Name: "Webhook test"}
		if err := postNotifyWebhook(ctx, provider, target, "FloweySales test notification", "Your flow notifications will arrive here.", "\n\n"+notifyDisclaimer, test, 0); err != nil {
			writeJSON(w, 502, map[string]string{"error": err.Error()})
			return
		}
		writeJSON(w, 200, map[string]bool{"sent": true})
	})
}
