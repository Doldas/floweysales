func TestJSONStructuredView(t *testing.T) {
	src := `{"symbol":"ALP","price":123.4500,"big":12345678901234567890,"currency":"USD","note":null,"ok":false,"empty":"",` +
		`"rows":[{"rank":1,"name":"Alpha","ret":"+3.1%"},{"rank":2,"name":"Beta","extra":true}],"tags":["a","b"],"meta":{"asOf":"2026-11-05T21:00:00Z"}}`
	r, err := Render(Message{Subject: "j", Kind: KindFlow, ContentType: JSON, Content: src, SentAt: fixedTime, Raw: true})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{">symbol<", "ALP", "123.4500", "12345678901234567890", ">note<", ">null<", ">false<", "&#34;&#34;", "+3.1%", "Alpha", "Beta", "2026-11-05T21:00:00Z", "Raw JSON"} {
		if !strings.Contains(r.HTML, want) {
			t.Errorf("HTML missing %q", want)
		}
	}
	// Source key order is kept.
	order := []string{">symbol<", ">price<", ">big<", ">currency<", ">note<", ">ok<", ">empty<"}
	pos := 0
	for _, k := range order {
		i := strings.Index(r.HTML[pos:], k)
		if i < 0 {
			t.Fatalf("key order broken at %s", k)
		}
		pos += i
	}
	if !strings.Contains(r.Text, "price: 123.4500") || !strings.Contains(r.Text, `"symbol":"ALP"`) {
		t.Errorf("text alternative incomplete:\n%s", r.Text)
	}
	if strings.Contains(r.HTML, "123.45<") {
		t.Error("number spelling was rewritten")
	}
}

func TestJSONDegradesGracefully(t *testing.T) {
	var sb strings.Builder
	sb.WriteString(`{"items":[`)
	for i := 0; i < 5000; i++ {
		if i > 0 {
			sb.WriteByte(',')
		}
		fmt.Fprintf(&sb, `{"i":%d,"name":"company %d","value":%d.5}`, i, i, i)
	}
	sb.WriteString(`],"deep":`)
	sb.WriteString(strings.Repeat(`{"a":`, 30) + `1` + strings.Repeat(`}`, 30) + `}`)
	r, err := Render(Message{Subject: "big", ContentType: JSON, Content: sb.String(), SentAt: fixedTime, FullOutput: "run #1"})
	if err != nil {
		t.Fatal(err)
	}
	if len(r.HTML) > maxHTMLBytes {
		t.Errorf("html %d bytes exceeds the clip limit", len(r.HTML))
	}
	if !strings.Contains(r.HTML, "more are omitted from this message") {
		t.Error("omission must be disclosed, not silent")
	}
	if !strings.Contains(r.Text, "omitted") {
		t.Error("omission must be disclosed in text too")
	}
	// Invalid and over-deep JSON fall back to the unchanged source, with a notice.
	r, _ = Render(Message{Subject: "bad", ContentType: JSON, Content: `{"a": [1,2`, SentAt: fixedTime})
	if !strings.Contains(r.HTML, "could not be parsed") || !strings.Contains(r.HTML, "[1,2") {
		t.Error("invalid JSON fallback")
	}
	r, _ = Render(Message{Subject: "deep", ContentType: JSON, Content: strings.Repeat("[", 100000) + strings.Repeat("]", 100000), SentAt: fixedTime})
	if !strings.Contains(r.HTML, "could not be parsed") {
		t.Error("over-deep JSON must fall back")
	}
}

