func TestSecurityMessagesKeepTokensSafe(t *testing.T) {
	const token = "SECRETTOKEN123"
	link := "https://app.example.com/?invite=" + token
	m := Message{Kind: KindTransactional, Subject: "FloweySales account invitation", Title: "Your research workspace awaits",
		Preheader: "You've been invited.", ContentType: Text, Content: "Activate.", SentAt: fixedTime,
		Action: &Action{Label: "Activate your account", URL: link}, ActionNote: "This invitation expires in 48 hours."}
	r, err := Render(m)
	if err != nil {
		t.Fatal(err)
	}
	pre := r.HTML[strings.Index(r.HTML, `mso-hide:all`):]
	pre = pre[:strings.Index(pre, "</div>")]
	if strings.Contains(pre, token) {
		t.Error("token must not appear in the preheader preview")
	}
	if !strings.Contains(r.HTML, `href="`+link+`"`) || !strings.Contains(r.Text, link) {
		t.Error("link missing in an alternative")
	}
	if !strings.Contains(r.Text, "expires in 48 hours") || !strings.Contains(r.HTML, "never asks you to send a password") {
		t.Error("security copy missing")
	}
	for _, bad := range []string{"javascript:alert(1)", "ftp://x.example/", "/relative", "https://u:p@x.example/"} {
		m.Action = &Action{Label: "x", URL: bad}
		if _, err := Render(m); err == nil {
			t.Errorf("unsafe action %q accepted", bad)
		}
	}
	// Errors never echo content or tokens.
	m.Action = &Action{Label: "x", URL: "javascript:" + token}
	if _, err := Render(m); err == nil || strings.Contains(err.Error(), token) {
		t.Errorf("error leaks token: %v", err)
	}
}

