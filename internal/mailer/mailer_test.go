func TestUnsafeLinksAreNotLinks(t *testing.T) {
	for _, u := range []string{"javascript:alert(1)", "JaVaScRiPt:alert(1)", "data:text/html;base64,AAAA", "vbscript:x", "//evil.example", "https://user:pw@evil.example/", "java\tscript:alert(1)", "file:///etc/passwd", "/relative", ""} {
		if _, ok := SafeURL(u); ok {
			t.Errorf("SafeURL accepted %q", u)
		}
	}
	for _, u := range []string{"https://example.com/a?b=c", "http://example.com", "mailto:a@example.com"} {
		if _, ok := SafeURL(u); !ok {
			t.Errorf("SafeURL refused %q", u)
		}
	}
	r, _ := Render(Message{Subject: "s", ContentType: Markdown, SentAt: fixedTime, Content: "[click](javascript:alert(1)) and https://bare.example/path"})
	if strings.Contains(r.HTML, "javascript:") {
		t.Error("unsafe URL reached the HTML")
	}
	if strings.Contains(r.HTML, `href="https://bare.example`) {
		t.Error("a bare string must not become a privileged link")
	}
}

func TestAdversarialContentIsInert(t *testing.T) {
	payloads := map[ContentType]string{
		Markdown: "<script>alert(1)</script> <img src=x onerror=alert(1)> [x](javascript:alert(1)) <a href=\"javascript:1\">x</a>\n\n| a | b |\n|---|---|\n| <b onclick=x>y</b> | \"quoted\" |",
		Text:     "<script>alert(1)</script>\n\n<style>body{display:none}</style>",
		JSON:     `{"<script>alert(1)</script>":"<img src=x onerror=alert(1)>","n":[{"a":"<svg onload=1>"}]}`,
		XML:      `<root onclick="x"><item a="&quot;&gt;&lt;script&gt;alert(1)&lt;/script&gt;">&lt;img src=x onerror=alert(1)&gt;</item></root>`,
		HTML: `<p onclick="x" style="position:fixed">hi</p><script>alert(1)</script><iframe src="https://evil"></iframe>` +
			`<a href="javascript:alert(1)">x</a><a href=" jav&#x61;script:alert(1)">y</a><a href="https://ok.example/">ok</a>` +
			`<!-- <script> --><style>@import url(https://evil)</style><img src=x onerror=alert(1)><svg><script>1</script></svg>` +
			`<div style="background:url(javascript:1)">kept text</div><form action="https://evil"><input name=p></form><object data=x></object>`,
	}
	for ct, content := range payloads {
		r, err := Render(Message{Subject: "t", Kind: KindFlow, ContentType: ct, Content: content, SentAt: fixedTime, Raw: true})
		if err != nil {
			t.Fatalf("%s: %v", ct, err)
		}
		// Strip the shell's own head, which legitimately has a style element.
		body := r.HTML[strings.Index(r.HTML, "<body"):]
		low := strings.ToLower(body)
		bads := []string{"<script", "<img", "<svg", "<iframe", "<object", "<form", "<input", "href=\"javascript", "<style"}
		if ct == HTML {
			// Escaped text is inert, but sanitized HTML must carry no such attributes at all.
			bads = append(bads, "onerror", "onclick", "onload", "javascript:", "@import", "position:fixed", "url(javascript")
		}
		for _, bad := range bads {
			if strings.Contains(low, bad) {
				t.Errorf("%s: output contains %q", ct, bad)
			}
		}
	}
	h, text := SanitizeHTML(payloads[HTML])
	if !strings.Contains(h, `href="https://ok.example/"`) || !strings.Contains(text, "kept text") || !strings.Contains(text, "https://ok.example/") {
		t.Errorf("allowed content lost: %s | %s", h, text)
	}
}

