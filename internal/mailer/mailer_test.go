func TestBuildIsMultipartAlternative(t *testing.T) {
	raw, err := Build("sender@example.com", "to@example.com", Message{Subject: "Zażółć → report", Kind: KindFlow, ContentType: Markdown, Content: "# Hi\n\nCafé **ok** — 100% done=yes", SentAt: fixedTime})
	if err != nil {
		t.Fatal(err)
	}
	msg, err := mail.ReadMessage(strings.NewReader(string(raw)))
	if err != nil {
		t.Fatal(err)
	}
	subj, _ := new(mime.WordDecoder).DecodeHeader(msg.Header.Get("Subject"))
	if subj != "Zażółć → report" {
		t.Errorf("subject %q", subj)
	}
	if msg.Header.Get("From") != "sender@example.com" || msg.Header.Get("To") != "to@example.com" || msg.Header.Get("MIME-Version") != "1.0" {
		t.Error("headers")
	}
	if d, err := msg.Header.Date(); err != nil || !d.Equal(fixedTime) || !strings.HasSuffix(msg.Header.Get("Date"), "+0000") {
		t.Errorf("date header %q", msg.Header.Get("Date"))
	}
	if !regexp.MustCompile(`^<[0-9a-f.]+@example\.com>$`).MatchString(msg.Header.Get("Message-ID")) {
		t.Errorf("message id %q", msg.Header.Get("Message-ID"))
	}
	typ, params, err := mime.ParseMediaType(msg.Header.Get("Content-Type"))
	if err != nil || typ != "multipart/alternative" {
		t.Fatalf("content type %q", typ)
	}
	mr := multipart.NewReader(msg.Body, params["boundary"])
	var types []string
	for {
		p, err := mr.NextRawPart()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		encoded, _ := io.ReadAll(p)
		body, _ := io.ReadAll(quotedprintable.NewReader(strings.NewReader(string(encoded))))
		types = append(types, strings.SplitN(p.Header.Get("Content-Type"), ";", 2)[0])
		for _, l := range strings.Split(string(encoded), "\n") {
			if len(l) > 998 {
				t.Errorf("line of %d bytes", len(l))
			}
		}
		if !strings.Contains(string(body), "100% done=yes") || !strings.Contains(string(body), "Café") {
			t.Errorf("%s part lost characters", p.Header.Get("Content-Type"))
		}
	}
	if strings.Join(types, ",") != "text/plain,text/html" {
		t.Errorf("parts %v: plain text must come first, HTML last", types)
	}
}

