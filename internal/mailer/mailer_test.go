func TestLeaderboardHasNoLeakedMarkdown(t *testing.T) {
	r, _ := Render(leaderboardMessage())
	body := r.HTML[strings.Index(r.HTML, "<h1"):]
	for _, bad := range []string{"**", "| ---", "|---", "| Rank |", "](http"} {
		if strings.Contains(body, bad) {
			t.Errorf("HTML leaks %q", bad)
		}
		if strings.Contains(r.Text, bad) {
			t.Errorf("text leaks %q", bad)
		}
	}
	if !strings.Contains(r.HTML, "<h1") || !strings.Contains(r.HTML, "Top 10 leaderboard") {
		t.Error("heading missing")
	}
	// Six columns become stacked cards on phones, not a table that scrolls.
	if strings.Contains(r.HTML, "<thead>") {
		t.Error("wide table should render as cards")
	}
	if !strings.Contains(r.HTML, ">1. Alpha Corp<") {
		t.Errorf("rank card title missing")
	}
	// Escaped, never interpreted.
	if !strings.Contains(r.HTML, "Beta &amp; Sons") || !strings.Contains(r.HTML, "Gamma &lt;Ltd&gt;") {
		t.Error("cell text is not escaped")
	}
	if !strings.Contains(r.HTML, `href="https://example.com/method?a=1&amp;b=2"`) {
		t.Error("link missing or unescaped")
	}
}

