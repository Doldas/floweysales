#!/usr/bin/env node
// One brand source for the app and the documentation site.
//
// frontend/public/icons and frontend/src/styles/_tokens.scss are canonical.
// This script copies the icons into site/icons and writes site/tokens.css from
// the two theme blocks of _tokens.scss. `--check` changes nothing and exits 1
// when a copy differs, which is how CI stops the site's brand from drifting.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const ICONS = ['icon.svg', 'icon-192.png', 'icon-512.png'];

/** Turns the two theme blocks of _tokens.scss into plain CSS for the site. */
export function tokensCss(scss) {
  const blocks = [...scss.matchAll(/^(:root,\s*\n\[data-bs-theme='light'\]|\[data-bs-theme='dark'\]) \{\n([\s\S]*?)\n\}/gm)];
  if (blocks.length !== 2) throw new Error('_tokens.scss: expected a light block and a dark block');
  const [light, dark] = blocks.map(b => b[2]);
  return [
    '/* Generated by scripts/sync-brand.mjs from frontend/src/styles/_tokens.scss. Do not edit. */',
    `:root, :root[data-theme='light'] {\n${light}\n}`,
    `:root[data-theme='dark'] {\n${dark}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${dark.replace(/^/gm, '  ')}\n  }\n}`,
    '',
  ].join('\n');
}

/** Returns the files that differ from their source (or are missing). */
export function syncBrand({ write, base = root } = {}) {
  const stale = [];
  const iconDir = join(base, 'site', 'icons');
  if (write) mkdirSync(iconDir, { recursive: true });
  for (const name of ICONS) {
    const from = join(base, 'frontend', 'public', 'icons', name);
    const to = join(iconDir, name);
    const same = existsSync(to) && readFileSync(from).equals(readFileSync(to));
    if (!same) { stale.push(`site/icons/${name}`); if (write) copyFileSync(from, to); }
  }
  const css = tokensCss(readFileSync(join(base, 'frontend', 'src', 'styles', '_tokens.scss'), 'utf8'));
  const cssPath = join(base, 'site', 'tokens.css');
  if (!existsSync(cssPath) || readFileSync(cssPath, 'utf8') !== css) { stale.push('site/tokens.css'); if (write) writeFileSync(cssPath, css); }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = syncBrand({ write: !check });
  if (check && stale.length) {
    console.error(`Brand copies are out of date: ${stale.join(', ')}\nRun: node scripts/sync-brand.mjs`);
    process.exit(1);
  }
  console.log(check ? 'Brand copies match the app.' : stale.length ? `Updated ${stale.join(', ')}` : 'Brand copies already match.');
}
